-- 009-ai-companions: AI 친구 (specs/009-ai-companions/data-model.md)
-- 반응 없는 글에 댓글과 공감을 남기는 AI 회원 셋, 글마다의 반응 기록, 하루의 몫.

-- member: 회원의 종류. AI 회원은 로그인 수단이 없고 직군과 경력이 없다(research R2)
ALTER TABLE member
  ADD COLUMN kind VARCHAR(10) NOT NULL DEFAULT 'HUMAN',
  ADD CONSTRAINT member_kind_check CHECK (kind IN ('HUMAN', 'AI'));

ALTER TABLE member DROP CONSTRAINT member_auth_method_check;
ALTER TABLE member
  ADD CONSTRAINT member_auth_method_check
    CHECK (auth_method IN ('EMAIL', 'KAKAO', 'GOOGLE', 'NONE')),
  ADD CONSTRAINT member_ai_auth_method_check
    CHECK ((kind = 'AI') = (auth_method = 'NONE')),
  ADD CONSTRAINT member_ai_no_credentials_check
    CHECK (kind <> 'AI' OR (email IS NULL AND password_hash IS NULL)),
  ADD CONSTRAINT member_ai_role_check
    CHECK (kind <> 'AI' OR role = 'MEMBER');

-- 사람은 지금 그대로다. AI는 닉네임만 있고 직군과 경력을 꾸며 넣을 수 없다
ALTER TABLE member DROP CONSTRAINT member_onboarding_fields_required_check;
ALTER TABLE member
  ADD CONSTRAINT member_onboarding_fields_required_check
    CHECK (
      (kind = 'HUMAN' AND (onboarded_at IS NULL
        OR (nickname IS NOT NULL AND nickname_key IS NOT NULL AND job_role IS NOT NULL AND career_year IS NOT NULL)))
      OR
      (kind = 'AI' AND onboarded_at IS NOT NULL AND nickname IS NOT NULL AND nickname_key IS NOT NULL
        AND job_role IS NULL AND career_year IS NULL)
    );

-- companion: AI 친구 한 명과 그 말씨. 다른 모듈의 테이블이라 member에 FK를 걸지 않는다
CREATE TABLE companion
(
  id         SMALLINT    NOT NULL,
  member_id  BIGINT      NOT NULL,
  voice      VARCHAR(10) NOT NULL,
  CONSTRAINT companion_pkey PRIMARY KEY (id),
  CONSTRAINT companion_member_key UNIQUE (member_id),
  CONSTRAINT companion_voice_key UNIQUE (voice),
  CONSTRAINT companion_voice_check CHECK (voice IN ('GENTLE', 'HEARTY', 'CALM'))
);

-- 닉네임에 띄어쓰기가 있어 사람의 닉네임(한글, 영문, 숫자)과 겹칠 수 없다(research R3)
WITH seed (id, nickname, voice) AS (
  VALUES (1, '다정한 오구', 'GENTLE'),
         (2, '씩씩한 오구', 'HEARTY'),
         (3, '차분한 오구', 'CALM')
),
inserted AS (
  INSERT INTO member (kind, auth_method, nickname, nickname_key, onboarded_at, created_at, updated_at)
  SELECT 'AI', 'NONE', nickname, lower(nickname), now(), now(), now()
  FROM seed
  ORDER BY id
  RETURNING id, nickname
)
INSERT INTO companion (id, member_id, voice)
SELECT seed.id, inserted.id, seed.voice
FROM seed
JOIN inserted ON inserted.nickname = seed.nickname;

-- companion_reaction: 글 하나에 대한 반응 한 건. 본문을 담지 않는다(FR-020)
CREATE TABLE companion_reaction
(
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
  post_id          BIGINT      NOT NULL,
  post_created_at  TIMESTAMPTZ NOT NULL,
  status           VARCHAR(10) NOT NULL,
  skip_reason      VARCHAR(20),
  companion_id     SMALLINT,
  comment_id       BIGINT,
  attempts         INT         NOT NULL DEFAULT 0,
  next_attempt_at  TIMESTAMPTZ,
  last_error       VARCHAR(100),
  created_at       TIMESTAMPTZ NOT NULL,
  completed_at     TIMESTAMPTZ,
  CONSTRAINT companion_reaction_pkey PRIMARY KEY (id),
  -- 한 글에 한 번을 지키는 것이 이 제약이다(research R4)
  CONSTRAINT companion_reaction_post_key UNIQUE (post_id),
  CONSTRAINT companion_reaction_status_check CHECK (status IN ('WAITING', 'DONE', 'SKIPPED')),
  CONSTRAINT companion_reaction_skip_reason_check
    CHECK (skip_reason IN ('HUMAN_COMMENT', 'RISK', 'GONE', 'EXPIRED', 'DAILY_LIMIT', 'FAILED', 'REJECTED')),
  CONSTRAINT companion_reaction_skip_check CHECK ((status = 'SKIPPED') = (skip_reason IS NOT NULL)),
  CONSTRAINT companion_reaction_done_check CHECK ((status = 'DONE') = (comment_id IS NOT NULL)),
  CONSTRAINT companion_reaction_waiting_check CHECK ((status = 'WAITING') = (next_attempt_at IS NOT NULL)),
  CONSTRAINT companion_reaction_completed_check CHECK ((status = 'WAITING') = (completed_at IS NULL))
);

-- 주기 작업이 먼저 올라온 글부터 맡는다
CREATE INDEX companion_reaction_due_idx ON companion_reaction (post_created_at) WHERE status = 'WAITING';
-- 가장 오래 쉰 친구를 고를 때 쓴다. 친구마다 가장 최근에 반응한 기록의 번호를 본다(시계에 기대지 않는다)
CREATE INDEX companion_reaction_done_idx ON companion_reaction (companion_id, id DESC) WHERE status = 'DONE';

-- companion_daily_usage: 하루(한국 시간)에 AI에 댓글을 청한 횟수(research R8)
CREATE TABLE companion_daily_usage
(
  day   DATE NOT NULL,
  used  INT  NOT NULL,
  CONSTRAINT companion_daily_usage_pkey PRIMARY KEY (day),
  CONSTRAINT companion_daily_usage_used_check CHECK (used >= 0)
);
