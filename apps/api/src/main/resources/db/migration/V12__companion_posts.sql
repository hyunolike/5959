-- 012-companion-activity (PR 2): 조용할 때 AI 친구가 고민 글을 쓴다 (specs/012-companion-activity/data-model.md)

-- posts: 글을 쓸 때의 글쓴이 종류를 직군, 경력과 같은 자리에 스냅숏으로 남긴다(research R10).
-- AI 친구의 글은 직군과 경력이 없다. 꾸며 낸 직군이 들어갈 자리를 제약으로 없앤다
ALTER TABLE posts
  ADD COLUMN author_kind VARCHAR(10) NOT NULL DEFAULT 'HUMAN',
  ALTER COLUMN author_job_role DROP NOT NULL,
  ALTER COLUMN author_career_year DROP NOT NULL;

ALTER TABLE posts
  ADD CONSTRAINT posts_author_kind_check CHECK (author_kind IN ('HUMAN', 'AI')),
  ADD CONSTRAINT posts_author_profile_check
    CHECK ((author_kind = 'AI') = (author_job_role IS NULL) AND (author_kind = 'AI') = (author_career_year IS NULL));

-- companion_post: AI 친구가 글을 쓰려 한 일 한 건. 본문을 담지 않는다(FR-037)
CREATE TABLE companion_post
(
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
  companion_id     SMALLINT    NOT NULL,
  day              DATE        NOT NULL,
  topic            VARCHAR(40) NOT NULL,
  comment_tone     VARCHAR(20) NOT NULL,
  status           VARCHAR(10) NOT NULL,
  give_up_reason   VARCHAR(20),
  post_id          BIGINT,
  attempts         INT         NOT NULL DEFAULT 0,
  next_attempt_at  TIMESTAMPTZ,
  last_error       VARCHAR(100),
  created_at       TIMESTAMPTZ NOT NULL,
  completed_at     TIMESTAMPTZ,
  CONSTRAINT companion_post_pkey PRIMARY KEY (id),
  -- 친구마다 하루(한국 시간) 하나를 지키는 것이 이 제약이다. 쓰지 못하고 그만둔 것도 그날의 자리를 쓴다(research R12)
  CONSTRAINT companion_post_companion_day_key UNIQUE (companion_id, day),
  CONSTRAINT companion_post_status_check CHECK (status IN ('WRITING', 'POSTED', 'GIVEN_UP')),
  CONSTRAINT companion_post_give_up_reason_check
    CHECK (give_up_reason IN ('NOT_QUIET', 'OFF_HOURS', 'EXPIRED', 'DAILY_LIMIT', 'FAILED', 'REJECTED')),
  CONSTRAINT companion_post_give_up_check CHECK ((status = 'GIVEN_UP') = (give_up_reason IS NOT NULL)),
  CONSTRAINT companion_post_posted_check CHECK ((status = 'POSTED') = (post_id IS NOT NULL)),
  CONSTRAINT companion_post_writing_check CHECK ((status = 'WRITING') = (next_attempt_at IS NOT NULL)),
  CONSTRAINT companion_post_completed_check CHECK ((status = 'WRITING') = (completed_at IS NULL)),
  CONSTRAINT companion_post_comment_tone_check
    CHECK (comment_tone IN ('VENT_WITH_ME', 'COMFORT_ME', 'WARM_ADVICE', 'MAKE_ME_LAUGH')),
  CONSTRAINT companion_post_attempts_check CHECK (attempts >= 0)
);

-- 쓰는 중인 행은 하나다. 여러 서버가 함께 조건을 보고 넣어도 하나만 들어간다(FR-022)
CREATE UNIQUE INDEX companion_post_writing_key ON companion_post ((1)) WHERE status = 'WRITING';
-- 그날의 올린 수와 청한 횟수를 센다
CREATE INDEX companion_post_day_idx ON companion_post (day);
