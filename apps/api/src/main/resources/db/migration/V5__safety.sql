-- post 모듈: 숨김과 단계 (research R5, R7, R11) -------------------------------

ALTER TABLE posts
  ADD COLUMN hidden_at            TIMESTAMPTZ,
  ADD COLUMN hidden_reason        VARCHAR(20),
  ADD COLUMN risk_level           VARCHAR(10) NOT NULL DEFAULT 'NONE',
  ADD COLUMN review_requested_at  TIMESTAMPTZ,
  -- 숨긴 시각과 이유는 함께 있거나 함께 없다
  ADD CONSTRAINT posts_hidden_pair_check CHECK ((hidden_at IS NULL) = (hidden_reason IS NULL)),
  ADD CONSTRAINT posts_hidden_reason_check CHECK (hidden_reason IS NULL OR hidden_reason IN ('RISK', 'OPERATOR')),
  ADD CONSTRAINT posts_risk_level_check CHECK (risk_level IN ('NONE', 'CONCERN', 'CRISIS'));

ALTER TABLE comments
  ADD COLUMN hidden_at            TIMESTAMPTZ,
  ADD COLUMN hidden_reason        VARCHAR(20),
  ADD COLUMN risk_level           VARCHAR(10) NOT NULL DEFAULT 'NONE',
  ADD COLUMN review_requested_at  TIMESTAMPTZ,
  ADD CONSTRAINT comments_hidden_pair_check CHECK ((hidden_at IS NULL) = (hidden_reason IS NULL)),
  ADD CONSTRAINT comments_hidden_reason_check CHECK (hidden_reason IS NULL OR hidden_reason IN ('RISK', 'OPERATOR')),
  ADD CONSTRAINT comments_risk_level_check CHECK (risk_level IN ('NONE', 'CONCERN', 'CRISIS'));

-- 다른 회원에게 보이는 글은 지우지 않았고 숨기지 않은 글이다. 피드 인덱스의 조건을 그에 맞춘다.
-- 내 글과 내 댓글 인덱스(posts_author_live_idx, comments_author_live_idx)는 그대로 둔다(작성자는 숨긴 것도 본다).
DROP INDEX posts_feed_latest_idx;
DROP INDEX posts_feed_popular_idx;
DROP INDEX posts_feed_author_profile_idx;
CREATE INDEX posts_feed_latest_idx ON posts (id DESC) WHERE deleted_at IS NULL AND hidden_at IS NULL;
CREATE INDEX posts_feed_popular_idx ON posts (like_count DESC, id DESC)
  WHERE deleted_at IS NULL AND hidden_at IS NULL;
CREATE INDEX posts_feed_author_profile_idx ON posts (author_job_role, author_career_year)
  WHERE deleted_at IS NULL AND hidden_at IS NULL;

