-- safety 모듈 -------------------------------------------------------------

-- 대상의 위험 판정 한 번. 대상이 고쳐지면 새 행이 생기고 가장 최근 행이 지금 상태다(research R3, R12).
-- 걸린 표현과 본문 사본은 저장하지 않는다(research R13).
CREATE TABLE risk_assessment
(
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
  target_type      VARCHAR(10) NOT NULL,
  target_id        BIGINT NOT NULL,
  post_id          BIGINT NOT NULL,
  author_id        BIGINT NOT NULL,
  -- 판정한 내용의 updated_at. 고친 뒤 늦게 온 분류 결과를 버리는 기준
  content_version  TIMESTAMPTZ NOT NULL,
  keyword_level    VARCHAR(10) NOT NULL,
  ai_level         VARCHAR(10),
  level            VARCHAR(10) NOT NULL,
  status           VARCHAR(10) NOT NULL,
  attempts         INT NOT NULL DEFAULT 0,
  next_attempt_at  TIMESTAMPTZ NOT NULL,
  last_error       VARCHAR(100),
  reviewed_at      TIMESTAMPTZ,
  created_at       TIMESTAMPTZ NOT NULL,
  completed_at     TIMESTAMPTZ,
  CONSTRAINT risk_assessment_pkey PRIMARY KEY (id),
  CONSTRAINT risk_assessment_target_type_check CHECK (target_type IN ('POST', 'COMMENT')),
  CONSTRAINT risk_assessment_keyword_level_check CHECK (keyword_level IN ('NONE', 'CONCERN', 'CRISIS')),
  CONSTRAINT risk_assessment_ai_level_check CHECK (ai_level IS NULL OR ai_level IN ('NONE', 'CONCERN', 'CRISIS')),
  CONSTRAINT risk_assessment_level_check CHECK (level IN ('NONE', 'CONCERN', 'CRISIS')),
  CONSTRAINT risk_assessment_status_check CHECK (status IN ('PENDING', 'DONE', 'FALLBACK', 'SUPERSEDED')),
  CONSTRAINT risk_assessment_attempts_check CHECK (attempts >= 0)
);

CREATE INDEX risk_assessment_target_idx ON risk_assessment (target_type, target_id, id DESC);
-- 재시도 스케줄러가 차례가 된 PENDING만 훑는다
CREATE INDEX risk_assessment_pending_idx ON risk_assessment (next_attempt_at) WHERE status = 'PENDING';
-- 운영자 조회
CREATE INDEX risk_assessment_level_idx ON risk_assessment (level, id DESC) WHERE level <> 'NONE';
-- 1년 정리
CREATE INDEX risk_assessment_created_at_idx ON risk_assessment (created_at);

CREATE TABLE report
(
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
  reporter_id  BIGINT NOT NULL,
  target_type  VARCHAR(10) NOT NULL,
  target_id    BIGINT NOT NULL,
  post_id      BIGINT NOT NULL,
  reason       VARCHAR(10) NOT NULL,
  -- 200글자(grapheme)까지. 결합 이모지를 생각해 넉넉히 둔다
  detail       VARCHAR(800),
  status       VARCHAR(10) NOT NULL,
  created_at   TIMESTAMPTZ NOT NULL,
  closed_at    TIMESTAMPTZ,
  CONSTRAINT report_pkey PRIMARY KEY (id),
  -- 같은 회원은 같은 대상을 한 번만 신고한다(ALREADY_REPORTED)
  CONSTRAINT report_reporter_target_key UNIQUE (reporter_id, target_type, target_id),
  CONSTRAINT report_target_type_check CHECK (target_type IN ('POST', 'COMMENT')),
  CONSTRAINT report_reason_check CHECK (reason IN ('DANGEROUS', 'ABUSIVE', 'SPAM', 'OTHER')),
  CONSTRAINT report_status_check CHECK (status IN ('PENDING', 'RESOLVED', 'REJECTED', 'CLOSED'))
);

CREATE INDEX report_status_idx ON report (status, id DESC);
-- 대상별 열린 신고 수와 한꺼번에 닫기
CREATE INDEX report_open_target_idx ON report (target_type, target_id) WHERE status = 'PENDING';
-- 한 시간 20건 제한
CREATE INDEX report_reporter_created_at_idx ON report (reporter_id, created_at);
CREATE INDEX report_created_at_idx ON report (created_at);

CREATE TABLE review_request
(
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
  target_type   VARCHAR(10) NOT NULL,
  target_id     BIGINT NOT NULL,
  post_id       BIGINT NOT NULL,
  requester_id  BIGINT NOT NULL,
  status        VARCHAR(10) NOT NULL,
  created_at    TIMESTAMPTZ NOT NULL,
  closed_at     TIMESTAMPTZ,
  CONSTRAINT review_request_pkey PRIMARY KEY (id),
  -- 대상마다 한 번만 요청한다(REVIEW_ALREADY_REQUESTED)
  CONSTRAINT review_request_target_key UNIQUE (target_type, target_id),
  CONSTRAINT review_request_target_type_check CHECK (target_type IN ('POST', 'COMMENT')),
  CONSTRAINT review_request_status_check CHECK (status IN ('PENDING', 'KEPT', 'RESTORED'))
);

CREATE INDEX review_request_status_idx ON review_request (status, id DESC);
CREATE INDEX review_request_created_at_idx ON review_request (created_at);

-- 운영자가 한 일의 기록. 고치거나 지우지 않는다(1년 정리만).
CREATE TABLE moderation_action
(
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
  operator_id  BIGINT NOT NULL,
  action       VARCHAR(20) NOT NULL,
  target_type  VARCHAR(10),
  target_id    BIGINT,
  note         VARCHAR(200),
  created_at   TIMESTAMPTZ NOT NULL,
  CONSTRAINT moderation_action_pkey PRIMARY KEY (id),
  CONSTRAINT moderation_action_action_check
    CHECK (action IN ('HIDE', 'UNHIDE', 'RESOLVE_REPORT', 'REJECT_REPORT', 'KEEP_HIDDEN', 'ADD_TERM', 'REMOVE_TERM')),
  CONSTRAINT moderation_action_target_type_check
    CHECK (target_type IS NULL OR target_type IN ('POST', 'COMMENT', 'TERM'))
);

CREATE INDEX moderation_action_created_at_idx ON moderation_action (created_at);
CREATE INDEX moderation_action_target_idx ON moderation_action (target_type, target_id);

-- 키워드 규칙과 욕설 가리기에 쓰는 낱말. term은 정규화한 형태다(research R4).
CREATE TABLE safety_term
(
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
  kind        VARCHAR(10) NOT NULL,
  term        VARCHAR(40) NOT NULL,
  created_at  TIMESTAMPTZ NOT NULL,
  updated_at  TIMESTAMPTZ NOT NULL,
  CONSTRAINT safety_term_pkey PRIMARY KEY (id),
  CONSTRAINT safety_term_kind_term_key UNIQUE (kind, term),
  CONSTRAINT safety_term_kind_check CHECK (kind IN ('CRISIS', 'CONCERN', 'PROFANITY', 'ALLOW'))
);

CREATE TABLE support_resource
