-- 012-companion-activity (PR 1): 한 글에 AI 친구가 한 명에서 세 명까지 반응한다
-- (specs/012-companion-activity/data-model.md)

-- companion_reaction: 글 하나에 대해 AI 친구들이 반응하는 과정. 여전히 글 하나에 한 행이다(research R1)
ALTER TABLE companion_reaction
  ADD COLUMN target_count SMALLINT NOT NULL DEFAULT 1,
  ADD COLUMN done_count   SMALLINT NOT NULL DEFAULT 0;

-- companion_reaction_entry: 한 글에 AI 친구 한 명이 남긴 반응 한 건
CREATE TABLE companion_reaction_entry
(
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
  reaction_id   BIGINT      NOT NULL,
  post_id       BIGINT      NOT NULL,
  companion_id  SMALLINT    NOT NULL,
  comment_id    BIGINT      NOT NULL,
  created_at    TIMESTAMPTZ NOT NULL,
  CONSTRAINT companion_reaction_entry_pkey PRIMARY KEY (id),
  CONSTRAINT companion_reaction_entry_reaction_fkey FOREIGN KEY (reaction_id) REFERENCES companion_reaction (id),
  -- 한 글에 같은 친구는 한 번을 지키는 것이 이 제약이다(research R1)
  CONSTRAINT companion_reaction_entry_post_companion_key UNIQUE (post_id, companion_id)
);

-- 가장 오래 쉰 친구를 고를 때 쓴다. 친구마다 가장 최근에 남긴 반응의 번호를 본다(시계에 기대지 않는다)
CREATE INDEX companion_reaction_entry_companion_idx ON companion_reaction_entry (companion_id, id DESC);
CREATE INDEX companion_reaction_entry_reaction_idx ON companion_reaction_entry (reaction_id);

-- 이미 반응한 기록을 옮긴다. 행의 번호 순서로 넣어 친구의 차례가 이어진다
INSERT INTO companion_reaction_entry (reaction_id, post_id, companion_id, comment_id, created_at)
SELECT id, post_id, companion_id, comment_id, coalesce(completed_at, created_at)
FROM companion_reaction
WHERE status = 'DONE' AND companion_id IS NOT NULL AND comment_id IS NOT NULL
ORDER BY id;

UPDATE companion_reaction SET done_count = 1 WHERE status = 'DONE';

-- DONE은 한 명 이상 반응하고 끝난 것, SKIPPED는 아무도 반응하지 않고 끝난 것이다. 한 명 이상 반응한 뒤 멈췄으면 DONE이고
-- skip_reason에 멈춘 까닭이 남는다
ALTER TABLE companion_reaction
  DROP CONSTRAINT companion_reaction_done_check,
  DROP CONSTRAINT companion_reaction_skip_check;

ALTER TABLE companion_reaction
  ADD CONSTRAINT companion_reaction_target_count_check CHECK (target_count BETWEEN 1 AND 3),
  ADD CONSTRAINT companion_reaction_done_count_check CHECK (done_count BETWEEN 0 AND target_count),
  ADD CONSTRAINT companion_reaction_done_check CHECK (status = 'WAITING' OR (status = 'DONE') = (done_count > 0)),
  ADD CONSTRAINT companion_reaction_skip_check
    CHECK ((status <> 'SKIPPED' OR skip_reason IS NOT NULL) AND (status <> 'WAITING' OR skip_reason IS NULL));

-- 가장 오래 쉰 친구는 이제 entry로 고른다
DROP INDEX companion_reaction_done_idx;
